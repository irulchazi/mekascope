import { expect, test } from '@playwright/test'
import path from 'node:path'

test('equipment and service records persist, edit, and supply inspection context', async ({ page, request }, testInfo) => {
  const name = `Road bike ${Date.now()}`
  await page.goto('/')
  await page.getByRole('link', { name: 'Equipment Configuration and details' }).click()
  await page.getByRole('button', { name: 'Add equipment', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Equipment name *').fill(name)
  await dialog.getByLabel('Manufacturer').fill('Element')
  await dialog.getByLabel('Model', { exact: true }).fill('FRC 50')
  await dialog.getByLabel('Serial / asset number').fill('BIKE-001')
  await dialog.getByLabel('Configuration notes').fill('Shimano 105; 11-speed drivetrain.\nOriginal cassette.')
  await dialog.getByRole('button', { name: 'Save equipment' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('status')).toHaveText('Equipment saved.')
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await dialog.getByLabel('Configuration notes').fill('Shimano 105; 11-speed drivetrain.\nReplacement cassette fitted.')
  await dialog.getByRole('button', { name: 'Save equipment' }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  await page.getByRole('searchbox').fill(name)
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(page.getByText('Replacement cassette fitted.', { exact: false })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('equipment-desktop.png'), fullPage: true })
  await page.getByRole('link', { name: 'Service history (0)' }).click()
  await page.getByRole('button', { name: 'Log service', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.locator('select[name="equipment_id"] option:checked')).toHaveText(name)
  await dialog.getByLabel('Service title *').fill('Chain and cassette service')
  await dialog.getByLabel('Service date *').fill('2026-10-01')
  await dialog.getByLabel('Service type *').selectOption('repair')
  await dialog.getByLabel('Performed by').fill('Workshop technician')
  await dialog.getByLabel('Work performed & observations *').fill('Replaced chain and checked shifting under load.')
  await dialog.getByRole('button', { name: 'Save service record' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('status')).toHaveText('Service record saved.')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Chain and cassette service' })).toBeVisible()
  await page.getByRole('button', { name: 'Edit Chain and cassette service' }).click()
  await dialog.getByLabel('Work performed & observations *').fill('Replaced chain; shifting verified in every gear.')
  await dialog.getByRole('button', { name: 'Save service record' }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('combobox', { name: 'Filter by service type' }).selectOption('inspection')
  await expect(page.getByRole('heading', { name: 'No matching service records.' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Filter by service type' }).selectOption('repair')
  await page.getByRole('searchbox').fill('every gear')
  await expect(page.locator('.service-entry')).toHaveCount(1)
  await page.screenshot({ path: testInfo.outputPath('service-history-desktop.png'), fullPage: true })
  await page.getByRole('link', { name, exact: true }).click()
  await page.getByRole('link', { name: 'Inspect equipment' }).click()
  await expect(page.getByRole('radio', { name: 'Upload photo' })).toBeChecked()
  await expect(page.getByLabel('Saved equipment (optional)').locator('option:checked')).toHaveText(name)
  await page.locator('input[type=file]').first().setInputFiles(path.resolve('public/images/bicycle-drivetrain.jpg'))
  await page.getByLabel('What do you notice?').fill('Clicking under load.')
  await page.getByRole('button', { name: 'Analyze photo' }).click()
  await expect(page.getByRole('button', { name: 'Explore equipment' })).toBeVisible()
  const caseId = await page.evaluate(() => JSON.parse(sessionStorage.getItem('mekascope-case-v2') || '{}').id)
  const saved = await (await request.get(`http://127.0.0.1:8011/api/v1/cases/${caseId}`)).json()
  expect(saved.context.name).toBe(name)
  expect(saved.context.configuration).toContain('Replacement cassette fitted.')
  expect(saved.context.service).toContain('shifting verified in every gear')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Explore equipment' })).toBeVisible()
  await expect(page).toHaveURL(new RegExp(`case=${caseId}`))
  await page.getByRole('button', { name: 'Explore equipment' }).click()
  await expect(page.getByText('Replacement cassette fitted.', { exact: false })).toBeVisible()
  await expect(page.getByText('shifting verified in every gear', { exact: false })).toBeVisible()
})

test('records recover from loading and saving errors without losing form input', async ({ page }) => {
  let loadingFailed = true
  let savingFailed = true
  await page.route('**/api/v1/equipment', async route => {
    if (route.request().method() === 'POST') {
      if (savingFailed) await route.fulfill({ status: 503, json: { detail: 'Save unavailable. Please retry.' } })
      else await route.continue()
    } else await route.fulfill(loadingFailed ? { status: 503, json: { detail: 'Records unavailable. Please retry.' } } : { json: [] })
  })
  await page.route('**/api/v1/service-records', route => route.fulfill({ json: [] }))
  await page.goto('/equipment')
  await expect(page.getByRole('alert')).toContainText('Records unavailable')
  loadingFailed = false
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Build your equipment memory.' })).toBeVisible()
  await page.getByRole('button', { name: 'Add first equipment' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Equipment name *').fill('Retry bike')
  await dialog.getByRole('button', { name: 'Save equipment' }).click()
  await expect(dialog.getByRole('alert')).toContainText('Save unavailable')
  await expect(dialog.getByLabel('Equipment name *')).toHaveValue('Retry bike')
  savingFailed = false
  await dialog.getByRole('button', { name: 'Save equipment' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Retry bike', exact: true })).toBeVisible()
})

test('equipment and service forms work on mobile and support keyboard dismissal', async ({ page, request }, testInfo) => {
  const result = await request.post('http://127.0.0.1:8011/api/v1/equipment', { data: { name: 'Mobile workshop bicycle', configuration: 'Compact drivetrain.' } })
  const equipment = await result.json()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`/equipment?equipment=${equipment.id}`)
  await expect(page.getByRole('heading', { name: equipment.name, exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('equipment-mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 320, height: 740 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('link', { name: 'Service history (0)' }).click()
  await page.getByRole('button', { name: 'Log service', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Service title *').fill('Mobile service entry')
  await dialog.getByLabel('Work performed & observations *').fill('Cleaned and lubricated chain.')
  await expect.poll(() => dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('service-form-mobile.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Save service record' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Mobile service entry' })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('service-history-mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 320, height: 740 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
