for (const width of [1440, 1024, 390]) {
  test(`portrait uploads fit the context layout and open a zoomable viewer at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    const preview = page.locator('.inspection-preview')
    await preview.locator('img').evaluate((image: HTMLImageElement) => image.decode())
    const original = await preview.boundingBox()
    expect(original).toBeTruthy()
    async function expectContextAlignment() {
      await expect.poll(async () => {
        const photo = await preview.locator('.visual-frame, .photo-placeholder').boundingBox()
        const column = await preview.boundingBox()
        return Math.max(Math.abs(photo!.x - column!.x), Math.abs(photo!.width - column!.width))
      }).toBeLessThan(1)
      if (width <= 700) return
      await expect.poll(async () => {
        const photo = await preview.locator('.visual-frame, .photo-placeholder').boundingBox()
        const context = await page.locator('.inspection-context').boundingBox()
        const note = await page.locator('.inspection-context .agent-note').boundingBox()
        expect(photo!.x + photo!.width).toBeLessThan(context!.x)
        return Math.abs(photo!.y + photo!.height - note!.y - note!.height)
      }).toBeLessThan(1)
    }
    await expectContextAlignment()
    await page.getByLabel('Upload photo', { exact: true }).check()
    const empty = await preview.boundingBox()
    if (width <= 700) expect(empty!.height).toBeCloseTo(original!.height, 0)
    await expectContextAlignment()
    await page.locator('.inspection-layout').screenshot({ path: testInfo.outputPath('empty-upload-preview.png') })
    const converted = page.waitForResponse('**/api/v1/images/preview')
    await page.getByLabel('Bicycle photo').setInputFiles('../app/tests/fixtures/iphone-photo.heic')
    expect((await converted).status()).toBe(200)
    await expect.poll(() => preview.locator('img').evaluate((image: HTMLImageElement) => image.naturalHeight > image.naturalWidth)).toBe(true)
    const portrait = await preview.boundingBox()
    expect(portrait!.height).toBeCloseTo(empty!.height, 0)
    expect(portrait!.width).toBeCloseTo(original!.width, 0)
    await expectContextAlignment()
    await expect(preview.locator('img')).toHaveCSS('object-fit', 'contain')
    await page.screenshot({ path: testInfo.outputPath('portrait-preview.png'), fullPage: true })

    const expand = page.getByRole('button', { name: 'Enlarge inspection photo' })
    await expand.click()
    const viewer = page.getByRole('dialog', { name: 'Inspection photo', exact: true })
    await expect(viewer).toBeVisible()
    expect(await page.evaluate(() => getComputedStyle(document.body).overflow)).toBe('hidden')
    await viewer.locator('img').evaluate((image: HTMLImageElement) => image.decode())
    const fitted = await viewer.locator('.photo-viewer-canvas').boundingBox()
    await viewer.getByRole('button', { name: 'Zoom in', exact: true }).click()
    await expect(viewer.getByRole('status')).toHaveText('150%')
    const zoomed = await viewer.locator('.photo-viewer-canvas').boundingBox()
    expect(zoomed!.height).toBeGreaterThan(fitted!.height * 1.4)
    await viewer.getByRole('button', { name: 'Zoom out', exact: true }).click()
    await expect(viewer.getByRole('status')).toHaveText('100%')
    await page.screenshot({ path: testInfo.outputPath('portrait-viewer.png') })
    await page.keyboard.press('Escape')
    await expect(page.locator('.photo-viewer')).toHaveCount(0)
    await expect(expand).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(viewer).toBeVisible()
    await viewer.getByRole('button', { name: 'Close photo viewer' }).click()
    await expect(viewer).toHaveCount(0)
    expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
    expect(await page.evaluate(() => getComputedStyle(document.body).overflow)).toBe('visible')
  })
}

test('an invalid HEIC shows an error and another photo can be selected', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Upload photo', { exact: true }).check()
  await page.getByLabel('Bicycle photo').setInputFiles({ name: 'broken.heic', mimeType: 'image/heic', buffer: Buffer.from('not a photo') })
  await expect(page.getByRole('alert')).toContainText('could not be decoded')
  await page.getByLabel('What do you notice?').fill('Clicking when shifting.')
  await expect(page.getByRole('button', { name: 'Analyze photo' })).toBeDisabled()
  await page.locator('input[capture="environment"]').setInputFiles('public/images/bicycle-drivetrain.jpg')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Analyze photo' })).toBeEnabled()
  // Camera selection satisfies the required photo field even when the file picker is empty.
  await page.getByRole('button', { name: 'Analyze photo' }).click()
  await expect(page.getByRole('button', { name: 'Explore equipment' })).toBeVisible()
})
