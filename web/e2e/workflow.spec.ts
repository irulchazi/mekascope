import { expect, test } from '@playwright/test'

test('sample case persists through verification, approval, resolution, and restart', async ({ page, request }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Analyze photo' }).click()
  await page.getByRole('button', { name: 'Explore equipment' }).click()
  await expect(page.getByText('Exact model unknown')).toHaveCount(0)
  await expect(page.locator('.component-card > p')).toHaveCount(1)
  await page.getByRole('main').getByRole('button', { name: 'Investigate', exact: true }).click()
  await page.getByRole('button', { name: 'Verify leading cause' }).click()
  await page.getByLabel('Observations: Inspect chain position').fill('Chain rubs the adjacent cog.')
  await page.getByRole('button', { name: 'Confirm check completed' }).first().click()
  await expect(page.getByRole('button', { name: 'Done', exact: true })).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Done', exact: true })).toBeDisabled()
  const completedObservations = page.getByLabel('Observations: Inspect chain position')
  await expect(completedObservations).toBeEditable()
  await completedObservations.fill('Chain rubs the adjacent cog; indexing checked again.')
  const observationSaved = page.waitForResponse(response => response.request().method() === 'PUT' && response.url().includes('/verification-steps/'))
  await completedObservations.blur()
  expect((await observationSaved).ok()).toBe(true)
  await expect(page.getByRole('button', { name: 'Done', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Next' }).click()
  await page.getByRole('button', { name: 'Confirm check completed' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Done' })).toHaveCount(1)
  await expect(page.getByLabel('Observations: Inspect chain position')).toHaveValue('Chain rubs the adjacent cog; indexing checked again.')
  await expect(page.getByLabel('Observations: Inspect chain position')).toBeEditable()
  await expect(page.getByRole('button', { name: 'Done', exact: true })).toBeDisabled()
  await request.post('http://127.0.0.1:8011/__test/pause')
  try {
    await completedObservations.fill('Final observations entered just before reassessment.')
    const reassess = page.getByRole('button', { name: 'Reassess diagnosis' })
    await reassess.scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => window.scrollY)).toBeGreaterThan(0)
    await reassess.click()
    await expect(completedObservations).toBeDisabled()
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
    await expect(page.getByRole('status').filter({ hasText: 'Reassessing the diagnosis…' })).toBeInViewport()
    const caseId = await page.evaluate(() => JSON.parse(sessionStorage.getItem('mekascope-case-v2')!).id as string)
    await expect.poll(async () => (await (await request.get(`http://127.0.0.1:8011/api/v1/cases/${caseId}`)).json()).operation).toBe('verify')
    const duringReview = await (await request.get(`http://127.0.0.1:8011/api/v1/cases/${caseId}`)).json()
    expect(duringReview.steps[0].observation).toBe('Final observations entered just before reassessment.')
  } finally { await request.post('http://127.0.0.1:8011/__test/release') }
  await expect(page.getByText('Review complete: inconclusive.')).toBeVisible()
  await expect(completedObservations).toBeDisabled()
  await page.getByRole('button', { name: 'Review action plan' }).click()
  await page.getByRole('button', { name: 'Approve & create task' }).click()
  await expect(page.getByRole('heading', { name: /Task #\d+/ })).toBeVisible()
  await page.getByLabel('Resolution notes (optional)').fill('Technician inspected and adjusted indexing.')
  await page.getByRole('button', { name: 'Mark issue resolved' }).click()
  await page.reload()
  await expect(page.getByText('Outcome added to the case memory')).toBeVisible()
  const id = await page.evaluate(() => JSON.parse(sessionStorage.getItem('mekascope-case-v2')!).id as string)
  await page.getByRole('button', { name: 'Explore pump preview' }).click()
  await expect(page.getByText('Preview only; no work order is created.')).toBeVisible()
  await page.getByRole('button', { name: 'Back to bicycle case' }).click()
  await page.getByRole('button', { name: 'New case', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Analyze photo' })).toBeVisible()
  const persisted = await request.get(`http://127.0.0.1:8011/api/v1/cases/${id}`)
  expect((await persisted.json()).task.status).toBe('resolved')
})

